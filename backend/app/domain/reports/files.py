def label(key: str, lang: Lang) -> str:
    return LABELS[key][lang == "en"]


def hours(minutes: int | None) -> float | None:
    return None if minutes is None else round(minutes / 60, 1)


def _cap(report: dict, lang: Lang) -> list[list]:
    overtime = report["overtime"]
    return [[
        row["code"], row["name"], label("yes" if row["active"] else "no", lang), hours(row["used"]), hours(row["planned"]),
        hours(overtime["limit"]), hours(row["remaining"]), hours(row["emergency"]), hours(row["absolute_total"]), hours(overtime["absolute_limit"]),
        label(row["status"], lang),
        label("complete", lang) if row["history_complete"] else f"{label('at_least', lang)} {overtime['known_from']}",
        row["projection_month"],
    ] for row in overtime["cap"]]


def _month(report: dict) -> list[list]:
    return [[row["code"], row["name"], hours(row["overtime"]), hours(row["work"]), row["days"], hours(row["year_average"])]
            for row in report["overtime"]["monthly"]]


def _coverage(report: dict, lang: Lang) -> list[list]:
    rows = []
    for row in report["coverage"]:
        days = row.get("days", [])
        notes = dict.fromkeys(f"{day['date']}: {day['note']}" for day in days if day["note"])
        cancellations = [f"{day['date']} {trip['trip_code']}: {trip['reason'] or ''}".rstrip(": ") for day in days for trip in day["cancelled"]]
        rows.append([
            " – ".join(names[lang == "en"] or names[0] or "" for names in row["names"]) or label("no_line", lang),
            row["scheduled"], row["covered"], row["uncovered"], row["cancelled"],
            None if row["rate"] is None else round(row["rate"] * 100, 1),
            "; ".join(f"{label(reason, lang)}: {count}" for reason, count in sorted(row["reasons"].items())),
            "\n".join(cancellations),
            "\n".join(notes),
        ])
    return rows


def sections(report: dict, lang: Lang) -> list[tuple[str, list[str], list[list]]]:
    def headers(*keys):
        return [label(key, lang) for key in keys]
    return [
        ("cap", headers("code", "driver", "active", "used", "planned", "limit", "remaining", "emergency", "absolute_total", "absolute_limit", "status", "history", "projection"), _cap(report, lang)),
        ("month", headers("code", "driver", "overtime", "work", "days", "year_average"), _month(report)),
        ("coverage", headers("line", "scheduled", "covered", "uncovered", "cancelled", "rate", "reasons", "cancellations", "notes"), _coverage(report, lang)),
    ]


def _about(meta: dict, lang: Lang) -> list[tuple[str, str]]:
    return [(label(key, lang), meta[key]) for key in ("organization", "month", "timezone", "generated_at", "generated_by", "published_days", "fingerprint")]


def _write(sheet, values: list, bold: bool = False) -> None:
    sheet.append([None] * len(values))
    for column, value in enumerate(values, 1):
        cell = sheet.cell(sheet.max_row, column)
        if isinstance(value, str):
            cell.value = ILLEGAL_CHARACTERS_RE.sub("", value)
            cell.data_type = "s"
        else:
            cell.value = value
        if bold:
            cell.font = Font(bold=True)


def xlsx_bytes(report: dict, lang: Lang, meta: dict) -> bytes:
    book = Workbook()
    book.remove(book.active)
    for key, headers, rows in sections(report, lang):
        sheet = book.create_sheet(label(key, lang))
        _write(sheet, headers, bold=True)
        for row in rows:
            _write(sheet, row)
        sheet.freeze_panes = "A2"
    about = book.create_sheet(label("about", lang))
    for pair in _about(meta, lang):
        _write(about, list(pair))
    _write(about, [label("statement", lang)])
    about.column_dimensions["A"].width = 28
    about.column_dimensions["B"].width = 40
    output = BytesIO()
    book.save(output)
    return output.getvalue()


def _paragraph(value, style) -> Paragraph:
    return Paragraph("" if value is None else escape(str(value)).replace("\n", "<br/>"), style)


def pdf_bytes(report: dict, lang: Lang, meta: dict) -> bytes:
    body = ParagraphStyle("body", fontName="DejaVu", fontSize=7, leading=9)
    head = ParagraphStyle("head", parent=body, fontName="DejaVu-Bold")
    heading = ParagraphStyle("heading", parent=head, fontSize=11, leading=14, spaceBefore=10, spaceAfter=4)
    title = ParagraphStyle("title", parent=head, fontSize=15, leading=19)
    info = ParagraphStyle("info", parent=body, fontSize=9, leading=12)
    output = BytesIO()
    document = SimpleDocTemplate(output, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm, topMargin=12 * mm, bottomMargin=14 * mm,
                                 title=f"{label('title', lang)} {meta['month']}", author=meta["organization"])
    story = [_paragraph(f"{meta['organization']} · {label('title', lang)} {meta['month']}", title)]
    story += [_paragraph(f"{name}: {value}", info) for name, value in _about(meta, lang)[2:]]
    story += [_paragraph(label("statement", lang), ParagraphStyle("statement", parent=info, fontName="DejaVu-Bold", spaceBefore=4))]
    for key, headers, rows in sections(report, lang):
        story.append(_paragraph(label(f"{key}_heading", lang), heading))
        cells = [[_paragraph(value, head) for value in headers]] + [[_paragraph(value, body) for value in row] for row in rows]
        table = Table(cells, colWidths=[document.width * weight / sum(WIDTHS[key]) for weight in WIDTHS[key]], repeatRows=1, splitInRow=1)
        table.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#9aa3ad")),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8ecf1")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story += [table, Spacer(1, 4)]

    def number(canvas, _):
        canvas.setFont("DejaVu", 8)
        canvas.drawRightString(landscape(A4)[0] - 12 * mm, 8 * mm, f"{label('page', lang)} {canvas.getPageNumber()}")

    document.build(story, onFirstPage=number, onLaterPages=number)
    return output.getvalue()
