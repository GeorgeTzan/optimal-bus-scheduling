from io import BytesIO
from openpyxl import load_workbook
from pypdf import PdfReader
from sqlalchemy import text
from tests.integration.test_identity import identity_setup
from tests.integration.test_office_permissions import person
from tests.integration.test_publish_reason import approved_day, publish_with
from tests.integration.test_reports_coverage import published_day
from tests.integration.test_work_rules_gates import FIRST

EXPORT = '/api/v1/reports/export'
NOTE = '=ΣΥΝΟΛΟ(A1)\n' + 'α' * 480


def management(setup):
    return person(setup, 'management@example.org', 'management')[0]


def get_export(setup, headers, format, lang, month='2026-06'):
    return setup['client'].get(EXPORT, headers=headers, params={'month': month, 'format': format, 'lang': lang})


def exports(setup, organization='first'):
    with setup['owner_factory']() as db:
        return db.execute(text('SELECT format, month, fingerprint, generated_by FROM domain_report_exports WHERE tenant_id=:t ORDER BY id'),
                          {'t': setup[organization].tenant_id}).all()


def column(sheet, header):
    return next(cell.column for cell in sheet[1] if cell.value == header)


def pdf_text(content):
    return '\n'.join(page.extract_text() for page in PdfReader(BytesIO(content)).pages)


def test_xlsx_has_sections_and_decimal_hours(identity_setup):
    client, operator, approved = approved_day(identity_setup, {'T1': FIRST, 'T2': FIRST})
    assert publish_with(client, operator, approved).status_code == 200
    headers = management(identity_setup)
    response = get_export(identity_setup, headers, 'xlsx', 'en')
    assert response.status_code == 200, response.text[:400]
    assert response.headers['content-disposition'] == 'attachment; filename="reports-2026-06.xlsx"'
    assert response.headers['content-type'] == 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    wb = load_workbook(BytesIO(response.content))
    assert wb.sheetnames == ['Cap', 'Month', 'Coverage', 'About']
    assert all(not wb[name].merged_cells.ranges for name in wb.sheetnames)
    body = identity_setup['client'].get('/api/v1/reports/monthly?month=2026-06', headers=headers).json()
    cap, first = wb['Cap'], body['overtime']['cap'][0]
    used = cap.cell(2, column(cap, 'Used (h)')).value
    assert isinstance(used, float) and used == round(first['used'] / 60, 1) > 0
    assert cap.cell(2, column(cap, 'Limit (h)')).value == 120 and cap.cell(2, column(cap, 'Status')).value == 'Within limits'
    assert cap.cell(2, column(cap, 'Driver')).value == first['name']
    assert cap.max_row == len(body['overtime']['cap']) + 1
    month, top = wb['Month'], body['overtime']['monthly'][0]
    assert month.cell(2, column(month, 'Overtime (h)')).value == round(top['overtime'] / 60, 1) > 0
    assert month.cell(2, column(month, 'Work (h)')).value == round(top['work'] / 60, 1)
    coverage = wb['Coverage']
    assert [coverage.cell(2, column(coverage, name)).value for name in ('Scheduled', 'Covered', 'Uncovered', 'Cancelled')] == [2, 2, 0, 0]
    assert coverage.cell(2, column(coverage, 'Coverage (%)')).value == 100
    assert coverage.cell(2, column(coverage, 'Line')).value == ' – '.join(names[1] or names[0] for names in body['coverage'][0]['names'])
    about = {row[0].value: row[1].value for row in wb['About'].iter_rows()}
    assert about['Organization'] == 'First KTEL' and about['Month'] == '2026-06' and about['Timezone'] == 'Europe/Athens'
    assert about['Generated by'] and about['Generated at']
    with identity_setup['owner_factory']() as db:
        stored = db.execute(text('SELECT fingerprint FROM domain_report_exports ORDER BY id')).scalar()
    assert about['Published days used since 1 Jan'] == 1 and about['Data fingerprint'] == stored[:12] and len(stored) == 64
    assert 'Planned figures from published schedules' in [cell.value for row in wb['About'].iter_rows() for cell in row]
    greek = load_workbook(BytesIO(get_export(identity_setup, headers, 'xlsx', 'el').content))
    assert greek.sheetnames == ['Όριο', 'Μήνας', 'Κάλυψη', 'Πληροφορίες']
    about = {row[0].value: row[1].value for row in greek['Πληροφορίες'].iter_rows()}
    assert about['Δημοσιευμένες ημέρες από 1 Ιαν.'] == 1 and about['Αποτύπωμα δεδομένων'] == stored[:12]


def test_pdf_is_pdf_and_records_download(identity_setup):
    from app.domain.reports.service import fingerprint
    published_day(identity_setup)
    headers = management(identity_setup)
    response = get_export(identity_setup, headers, 'pdf', 'el')
    assert response.status_code == 200, response.text[:400]
    assert response.content[:4] == b'%PDF' and response.headers['content-type'] == 'application/pdf'
    assert response.headers['content-disposition'] == 'attachment; filename="reports-2026-06.pdf"'
    assert b'DejaVu' in response.content
    words = pdf_text(response.content)
    assert 'Προγραμματισμένα στοιχεία από δημοσιευμένα προγράμματα' in words and 'First KTEL' in words and 'Νίκος Δήμου' in words
    english = pdf_text(get_export(identity_setup, headers, 'pdf', 'en').content)
    assert 'Planned figures from published schedules' in english
    rows = exports(identity_setup)
    assert f'Αποτύπωμα δεδομένων: {rows[0].fingerprint[:12]}' in words and 'Δημοσιευμένες ημέρες από 1 Ιαν.: 1' in words
    assert f'Data fingerprint: {rows[1].fingerprint[:12]}' in english and 'Published days used since 1 Jan: 1' in english
    assert [row.format for row in rows] == ['pdf', 'pdf'] and str(rows[0].month) == '2026-06-01'
    with identity_setup['owner_factory']() as db:
        assert rows[0].fingerprint == fingerprint(db, identity_setup['first'].tenant_id, rows[0].month)
    assert exports(identity_setup, 'second') == []
    body = identity_setup['client'].get('/api/v1/reports/monthly?month=2026-06', headers=headers).json()
    assert body['last_export']['format'] == 'pdf' and body['changed_since_export'] is False


def test_formula_like_note_is_text_and_pdf_renders_greek(identity_setup):
    client, operator, approved = approved_day(identity_setup, {'T1': FIRST})
    assert publish_with(client, operator, approved, uncovered_reason='other', uncovered_note=NOTE).status_code == 200
    headers = management(identity_setup)
    sheet = load_workbook(BytesIO(get_export(identity_setup, headers, 'xlsx', 'el').content))['Κάλυψη']
    cell = sheet.cell(2, column(sheet, 'Σημειώσεις'))
    assert cell.data_type == 's' and cell.value.startswith('2026-06-01: =ΣΥΝΟΛΟ') and cell.value.endswith('α' * 480)
    assert sheet.cell(2, column(sheet, 'Αιτίες')).value == 'Άλλο: 1' and sheet.cell(2, column(sheet, 'Κάλυψη (%)')).value == 50
    from app.domain.reports.files import xlsx_bytes
    meta = {'organization': '=1+1', 'month': '2026-06', 'generated_at': '2026-06-30 10:00', 'generated_by': '@user', 'timezone': 'Europe/Athens', 'published_days': 30, 'fingerprint': 'abcdef012345'}
    report = {'overtime': {'limit': 7200, 'absolute_limit': 10800, 'known_from': '2026-01-01', 'cap': [{'code': '+D', 'name': '-Name', 'active': True, 'used': 90, 'planned': 0, 'remaining': 0, 'emergency': 0,
                                    'absolute_total': 90, 'status': 'within', 'history_complete': False, 'projection_month': None}], 'monthly': []},
              'coverage': [{'names': [['Α', 'A'], ['Β', 'B']], 'scheduled': 62, 'covered': 0, 'uncovered': 62, 'cancelled': 0, 'rate': 0.0, 'reasons': {'other': 62},
                            'days': [{'date': f'2026-06-{day:02d}', 'note': f'{day} {NOTE}', 'cancelled': []} for day in range(1, 31)]}]}
    made = load_workbook(BytesIO(xlsx_bytes(report, 'en', meta)))
    for found in (made['Cap'].cell(2, 1), made['Cap'].cell(2, 2), made['About'].cell(1, 2), made['About'].cell(5, 2)):
        assert found.data_type == 's' and found.value[0] in '=+-@'
    assert made['Cap'].cell(2, column(made['Cap'], 'Used (h)')).value == 1.5
    assert made['Cap'].cell(2, column(made['Cap'], 'History')).value == 'At least; history unknown before 2026-01-01'
    from app.domain.reports.files import pdf_bytes
    assert len(PdfReader(BytesIO(pdf_bytes(report, 'el', meta))).pages) > 1
    response = get_export(identity_setup, headers, 'pdf', 'el')
    assert response.status_code == 200 and response.content[:4] == b'%PDF'
    assert 'ΣΥΝΟΛΟ' in pdf_text(response.content)


def test_export_requires_reports_read(identity_setup):
    published_day(identity_setup)
    for role in ('viewer', 'dispatcher'):
        headers, _ = person(identity_setup, f'{role}@example.org', role)
        assert get_export(identity_setup, headers, 'pdf', 'el').status_code == 403
    assert identity_setup['client'].get(EXPORT, params={'month': '2026-06', 'format': 'pdf', 'lang': 'el'}).status_code in (401, 403)
    assert exports(identity_setup) == []


def test_export_validates_parameters_and_isolates_organizations(identity_setup):
    published_day(identity_setup)
    headers = management(identity_setup)
    assert get_export(identity_setup, headers, 'csv', 'el').status_code == 422
    assert get_export(identity_setup, headers, 'pdf', 'de').status_code == 422
    assert get_export(identity_setup, headers, 'pdf', 'el', month='2099-01').status_code == 422
    assert exports(identity_setup) == []
    other, _ = person(identity_setup, 'management2@example.org', 'management', tenant='second')
    wb = load_workbook(BytesIO(get_export(identity_setup, other, 'xlsx', 'en').content))
    assert wb['Coverage'].max_row == 1 and wb['Month'].max_row == 1
    assert {row[0].value: row[1].value for row in wb['About'].iter_rows()}['Organization'] == 'Second KTEL'
    assert [row.format for row in exports(identity_setup, 'second')] == ['xlsx'] and exports(identity_setup) == []
